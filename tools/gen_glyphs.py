"""Regenerate asciivid/glyphs.py: per-glyph ink coverage on a sub-cell grid.

Each printable ASCII character is drawn into one terminal cell (font advance x
line height) at a large size, then averaged down to GRID_W x GRID_H. The
renderer matches every cell of a video frame against these masks to pick the
character whose shape fits best.

Needs Pillow and a monospace font; only the generated file ships.

    python3 tools/gen_glyphs.py [/path/to/font.ttf]
"""

import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

GRID_W, GRID_H = 4, 8
SIZE = 200
FONT = sys.argv[1] if len(sys.argv) > 1 else "/System/Library/Fonts/Menlo.ttc"

font = ImageFont.truetype(FONT, SIZE)
ascent, descent = font.getmetrics()
cell_w = round(font.getlength("M"))
cell_h = ascent + descent
# Make the cell divide evenly into the grid.
cell_w -= cell_w % GRID_W
cell_h -= cell_h % GRID_H

rows = []
for code in range(32, 127):
    ch = chr(code)
    img = Image.new("L", (cell_w, cell_h), 0)
    ImageDraw.Draw(img).text((0, 0), ch, fill=255, font=font)
    small = img.resize((GRID_W, GRID_H), Image.Resampling.BOX)
    values = [round(v / 255, 3) for v in small.tobytes()]
    rows.append((ch, values))

out = Path(__file__).resolve().parent.parent / "asciivid" / "glyphs.py"
with out.open("w") as f:
    f.write('"""Generated by tools/gen_glyphs.py. Do not edit."""\n\n')
    f.write(f"GRID_W, GRID_H = {GRID_W}, {GRID_H}\n")
    f.write(f"FONT = {Path(FONT).name!r}\n\n")
    f.write("# char -> ink coverage (0..1), row-major, GRID_W x GRID_H\n")
    f.write("MASKS = {\n")
    for ch, values in rows:
        f.write(f"    {ch!r}: {values},\n")
    f.write("}\n")
print(f"wrote {out} ({len(rows)} glyphs, cell {cell_w}x{cell_h})")
